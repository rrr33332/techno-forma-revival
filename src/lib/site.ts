/** Ukrainian numbers are stored in local format — build a valid tel: link. */
export function telHref(phone: string) {
  const digits = phone.replace(/\D/g, "");
  return `tel:+38${digits.startsWith("38") ? digits.slice(2) : digits}`;
}

