/** Preserves capitalisation of the source word when the target starts lowercase. */
function keepCase(source: string, target: string): string {
  if (!source || !target) return target;
  if (source[0] === source[0]?.toUpperCase() && source[0] !== source[0]?.toLowerCase()) {
    return target[0]!.toUpperCase() + target.slice(1);
  }
  return target;
}

export function toUkrainian(input: string | null | undefined): string {
  if (!input) return "";
  let out = input;

  for (const [pattern, replacement] of PHRASES) {
    out = out.replace(pattern, (match) => keepCase(match, replacement));
  }

  // Remaining russian-only letters that never appear in Ukrainian.
  out = out
    .replace(/ы/g, "и")
    .replace(/Ы/g, "И")
    .replace(/э/g, "е")
    .replace(/Э/g, "Е")
    .replace(/ъ/g, "'")
    .replace(/ё/g, "е")
    .replace(/Ё/g, "Е");

  return out;
}
